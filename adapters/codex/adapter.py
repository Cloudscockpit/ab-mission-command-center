"""OpenAI Codex CLI: dist/codex mirrors a project root (or $HOME for a global
install): skills in .agents/skills, custom agents in .codex/agents/*.toml,
hooks in .codex/hooks.json, approval rules in .codex/rules/.

Codex has no custom commands (prompts are deprecated and user-level only), so
/start-mission ships as the `start-mission` skill (`$start-mission <objective>`)
and the session itself plays Black Agent. That also respects Codex's default
agent depth of 1: the root session spawns the specialists, they spawn nothing.

Hooks cannot "ask" in Codex; asks go to .codex/rules (decision = "prompt").
__PYTHON__ and __HOOKS_DIR__ in hooks.json are filled in by scripts/install.py.
"""

import json
from collections import OrderedDict

from aflib.common import agent_body, command_as_skill, context7_toml, plain_skill
from aflib.model import adapter_file, adapter_tree, bash_mode, caps

NAME = "codex"
LABEL = "Codex CLI"
MODELS = {}  # omitted -> [agents] default_subagent_model, then the parent's model

TOOLS = {
    "dispatch": "`spawn_agent` with the agent name, then `wait_agent` for its report",
    "parallel": "Call `spawn_agent` for every independent agent first, then `wait_agent` for all of them.",
    "skill": "its name (`$skill-name`), or by reading its SKILL.md",
    "skill_creator": ("the `$skill-creator` skill when it is available, otherwise a new "
                      "`.agents/skills/<name>/SKILL.md` (`name` and `description` frontmatter)"),
    "reload": "after Codex is restarted",
    "read": "a shell read (`cat`, `sed -n`)",
    "glob": "`rg --files`",
    "grep": "`rg`",
    "shell": "shell",
    "webfetch": "web search",
}

GLOSSARY = [
    ("Read a file", "shell (`cat`, `sed -n`)", "read"), ("Create or edit a file", "`apply_patch`", "write|edit"),
    ("Find files by name", "`rg --files`", "read"), ("Search file contents", "`rg`", "read"),
    ("Run a shell command", "shell", "bash"), ("Fetch a URL / search the web", "web search", "webfetch|websearch"),
    ("Dispatch a subagent", "`spawn_agent`, then `wait_agent`", "delegate"),
    ("Load a skill", "`$skill-name` or read its SKILL.md", "skills"),
]

AGENTS_MD = """\
<!-- actionboard:begin -->
## ActionBoard V5 Agent Formation

Run `$start-mission <objective>` to plan a mission: this session acts as Black Agent,
spawns `green-agent` for recon, drafts the Mission Brief, Agent Assignments (with file
ownership), Skills Gap and Risk Register, then STOPS for go/no-go. After "go" it spawns
`red-agent`, `blue-agent` and `yellow-agent` (custom agents in `.codex/agents/`).

- Only spawn the ActionBoard agents when a mission is running.
- Specialists never spawn other agents and never commit.
- `openshell` commands are checked by the ActionBoard hook (`.codex/hooks.json`) and
  `.codex/rules/actionboard.rules`.
<!-- actionboard:end -->
"""


def _toml_str(s):
    return json.dumps(s, ensure_ascii=False)


def _toml_ml(s):
    if "'''" in s:
        raise ValueError("developer_instructions cannot contain '''")
    return "'''\n" + s.rstrip("\n") + "\n'''"


def agent_toml(agent, models):
    c = caps(agent)
    lines = ["# Generated by scripts/build.py from src/agents/%s.md - do not edit." % agent.name,
             "name = " + _toml_str(agent.name),
             "description = " + _toml_str(agent.meta["description"])]
    tier = agent.meta.get("model_tier", "inherit")
    if models.get(tier):
        lines.append("model = " + _toml_str(models[tier]))
    if models.get(tier + "_effort"):
        lines.append("model_reasoning_effort = " + _toml_str(models[tier + "_effort"]))
    lines.append("developer_instructions = " + _toml_ml(agent_body(agent, NAME, TOOLS, LABEL, GLOSSARY)))
    if bash_mode(c["bash"]) == "deny":
        lines += ["", "[features]", "shell_tool = false"]
    return "\n".join(lines) + "\n"


def build(src, out, models):
    models = dict(MODELS, **models)
    for a in src.agents:
        if not a.for_target(NAME) or a.meta.get("role") == "primary":
            continue  # primary agents are played by the root session via their command skill
        out.add(".codex/agents/%s.toml" % a.name, agent_toml(a, models))

    for s in src.skills:
        if not s.for_target(NAME):
            continue
        text, files = plain_skill(s, NAME, TOOLS)
        out.add(".agents/skills/%s/SKILL.md" % s.name, text)
        out.add_tree(".agents/skills/%s/" % s.name, files)
        if s.meta.get("invocation") == "user":
            out.add(".agents/skills/%s/agents/openai.yaml" % s.name,
                    "policy:\n  allow_implicit_invocation: false\n")

    for c in src.commands:
        text, files = command_as_skill(src, c, NAME, TOOLS, LABEL, GLOSSARY)
        out.add(".agents/skills/%s/SKILL.md" % c.name, text)
        out.add_tree(".agents/skills/%s/" % c.name, files)

    out.add(".codex/hooks.json", adapter_file("codex", "hooks.json"))
    out.add(".codex/rules/actionboard.rules", adapter_file("codex", "actionboard.rules"))
    out.add_tree(".codex/actionboard/hooks/", adapter_tree("common", "hooks"))
    out.add_tree(".codex/actionboard/hooks/core/", src.hooks_core)
    out.add("AGENTS.actionboard.md", AGENTS_MD)
    # Appended to .codex/config.toml by scripts/install.py unless context7 is already configured.
    out.add(".codex/actionboard/mcp.toml", context7_toml())
